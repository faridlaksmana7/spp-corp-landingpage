(function() {
  var preloader = document.getElementById('spp-preloader');
  var lottieContainer = document.getElementById('spp-lottie-container');
  var percentEl = document.getElementById('spp-loader-percent');
  var barEl = document.getElementById('spp-loader-bar');
  var statusEl = document.getElementById('spp-loader-status');

  if (!preloader) return;

  // Lock scroll immediately while preloading
  document.documentElement.classList.add('spp-loading');
  document.body.classList.add('spp-loading');

  // 1. Initialize Lottie Animation with Bodymovin SVG renderer
  var anim = null;
  function startLottie() {
    if (window.lottie && lottieContainer && window.SPP_LOTTIE_DATA) {
      try {
        anim = lottie.loadAnimation({
          container: lottieContainer,
          renderer: 'svg',
          loop: true,
          autoplay: true,
          animationData: window.SPP_LOTTIE_DATA
        });
      } catch (err) {
        console.warn('SPP Lottie initialization note:', err);
      }
    }
  }

  if (window.lottie) {
    startLottie();
  } else {
    // If lottie script is still streaming, wait for it
    var checkLottieInterval = setInterval(function() {
      if (window.lottie) {
        clearInterval(checkLottieInterval);
        startLottie();
      }
    }, 20);
    setTimeout(function() { clearInterval(checkLottieInterval); }, 1500);
  }

  // 2. Asset Discovery & Tracking
  var criticalAssets = [
    'assets/imgs/template/logo/spp-logo-white.png',
    'assets/imgs/brand/client-logos.gif',
    'assets/imgs/about/spp-hardware-mixer.webp',
    'assets/imgs/icons/client-pertamina.webp',
    'assets/imgs/icons/client-mandiri.webp',
    'assets/imgs/icons/client-gojek.webp',
    'assets/imgs/icons/client-antv.webp',
    'assets/imgs/icons/client-gacoan.webp',
    'assets/imgs/icons/client-dewaunited.webp'
  ];

  var allTrackedUrls = criticalAssets.slice();

  // Find images already present in HTML
  var foundImages = document.querySelectorAll('img');
  for (var i = 0; i < foundImages.length && i < 25; i++) {
    var src = foundImages[i].getAttribute('src');
    if (src && allTrackedUrls.indexOf(src) === -1) {
      allTrackedUrls.push(src);
    }
  }

  var totalWeight = allTrackedUrls.length + 3; // +1 for fonts, +1 for DOMContentLoaded, +1 for window.load
  var loadedUnits = 0;

  function markUnitLoaded() {
    loadedUnits++;
  }

  // Track fonts
  if (document.fonts && document.fonts.ready) {
    document.fonts.ready.then(markUnitLoaded).catch(markUnitLoaded);
  } else {
    markUnitLoaded();
  }

  // Track DOMContentLoaded
  if (document.readyState === 'interactive' || document.readyState === 'complete') {
    markUnitLoaded();
  } else {
    document.addEventListener('DOMContentLoaded', markUnitLoaded, { once: true });
  }

  // Track window load
  if (document.readyState === 'complete') {
    markUnitLoaded();
  } else {
    window.addEventListener('load', markUnitLoaded, { once: true });
  }

  // Track visual images
  allTrackedUrls.forEach(function(url) {
    var img = new Image();
    img.onload = markUnitLoaded;
    img.onerror = markUnitLoaded; // Do not hang if an image 404s
    img.src = url;
  });

  // 3. Realistic Dynamic Status Text
  var statusPhases = [
    { threshold: 0, text: 'INITIALIZING CREATIVE ENGINE...' },
    { threshold: 22, text: 'PRELOADING ULTRA-HD VISUALS...' },
    { threshold: 52, text: 'SYNCHRONIZING BRAND ASSETS...' },
    { threshold: 78, text: 'CALIBRATING GSAP SMOOTHER...' },
    { threshold: 96, text: 'PREPARING DISPLAY MESH...' },
    { threshold: 100, text: 'SYSTEM READY' }
  ];

  function getStatusText(pct) {
    for (var idx = statusPhases.length - 1; idx >= 0; idx--) {
      if (pct >= statusPhases[idx].threshold) {
        return statusPhases[idx].text;
      }
    }
    return 'INITIALIZING CREATIVE ENGINE...';
  }

  // 4. Smooth Counter Interpolation Loop
  var currentDisplayPct = 0;
  var isCompleted = false;
  var startTime = performance.now();
  var minDisplayDuration = 850; // Milliseconds to appreciate visual polish
  var maxFailsafeTimeout = 3200; // Never block user longer than 3.2s

  function triggerReveal() {
    if (isCompleted) return;
    isCompleted = true;

    currentDisplayPct = 100;
    if (percentEl) percentEl.textContent = '100';
    if (barEl) barEl.style.width = '100%';
    if (statusEl) {
      statusEl.textContent = 'SYSTEM READY';
      statusEl.style.color = '#00B2FE';
    }

    // Brief 240ms pause at 100% so user registers completion
    setTimeout(function() {
      preloader.classList.add('spp-loaded');
      document.documentElement.classList.remove('spp-loading');
      document.body.classList.remove('spp-loading');

      // Refresh ScrollTrigger and ScrollSmoother calculations now that DOM is 100% stable
      setTimeout(function() {
        if (window.ScrollTrigger) {
          try {
            window.ScrollTrigger.refresh(true);
          } catch(e) {}
        }
        window.dispatchEvent(new Event('resize'));
      }, 120);

      // Clean removal from DOM after slide-up curtain finishes
      setTimeout(function() {
        if (anim && typeof anim.destroy === 'function') {
          try { anim.destroy(); } catch(e) {}
        }
        preloader.style.display = 'none';
      }, 950);
    }, 240);
  }

  function frameLoop(now) {
    if (isCompleted) return;

    var elapsed = now - startTime;
    var rawRatio = Math.min(1, loadedUnits / Math.max(1, totalWeight));
    var targetPct = Math.min(99, Math.round(rawRatio * 100));

    // Check completion criteria
    if ((elapsed >= minDisplayDuration && loadedUnits >= totalWeight) || elapsed >= maxFailsafeTimeout) {
      triggerReveal();
      return;
    }

    // Interpolate smoothly toward target
    var delta = targetPct - currentDisplayPct;
    if (delta > 0) {
      var step = Math.max(0.4, delta * 0.15);
      currentDisplayPct = Math.min(targetPct, currentDisplayPct + step);
    } else {
      // Natural creeping increment while assets stream
      currentDisplayPct = Math.min(99, currentDisplayPct + 0.18);
    }

    var intVal = Math.floor(currentDisplayPct);
    if (percentEl) percentEl.textContent = intVal;
    if (barEl) barEl.style.width = currentDisplayPct + '%';
    if (statusEl) statusEl.textContent = getStatusText(intVal);

    requestAnimationFrame(frameLoop);
  }

  requestAnimationFrame(frameLoop);
})();
